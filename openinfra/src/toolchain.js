/**
 * The lockfile is the contract between "what a human installed" and "what the agent is allowed to run".
 *
 * bash-first means the shell resolves binaries by PATH, which is exactly how a stale or wrong `tofu` gets run.
 * So the tool env we hand to every child puts the pinned toolchain first, and `oi doctor` checks that each
 * locked binary still exists and still matches its recorded hash of `--version`.
 */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { parseToml, stringifyToml } from './toml.js'
import { workspacePaths, paths } from './paths.js'

export const TOOL_BINARIES = {
  tofu: 'tofu',
  terraform: 'terraform',
  ansible: 'ansible',
  'ansible-playbook': 'ansible-playbook',
  kubectl: 'kubectl',
  helm: 'helm',
  uv: 'uv',
  python: 'python3',
}

export function readLock(root) {
  const file = workspacePaths(root).lock
  if (!fs.existsSync(file)) return { file, tools: [], exists: false }
  try {
    const parsed = parseToml(fs.readFileSync(file, 'utf8'))
    return { file, tools: parsed.tool || [], pinned: parsed.pinned || {}, exists: true }
  } catch (err) {
    return { file, tools: [], exists: true, error: err.message }
  }
}

export function lockHash(tools) {
  const canon = JSON.stringify(
    tools
      .map((t) => ({ name: t.name, version: t.version, provider: t.provider, digest: t.digest }))
      .sort((a, b) => a.name.localeCompare(b.name)),
  )
  return crypto.createHash('sha256').update(canon).digest('hex')
}

export function toolDir(name, version) {
  return path.join(paths.toolchains, name, version)
}

/** PATH additions and explicit env for every child process we spawn on the workspace's behalf. */
export function toolEnv(root = null) {
  const env = { OPENINFRA_TOOLS: paths.toolchains }
  if (!root) return { env, path: [] }
  const lock = readLock(root)
  const dirs = new Set()
  for (const t of lock.tools) {
    if (t.path) dirs.add(t.path)
    else if (t.name && t.version) dirs.add(path.join(toolDir(t.name, t.version), 'bin'))
  }
  for (const d of [...dirs]) {
    if (!fs.existsSync(d)) dirs.delete(d)
  }
  return { env, path: [...dirs] }
}

export function findTool(root, name) {
  const lock = readLock(root)
  const entry = lock.tools.find((t) => t.name === name)
  if (!entry) return null
  if (entry.path && fs.existsSync(entry.path)) return entry.path
  const candidate = path.join(toolDir(entry.name, entry.version), 'bin', TOOL_BINARIES[name] || name)
  return fs.existsSync(candidate) ? candidate : null
}

export function versionFingerprint(binary) {
  try {
    const st = fs.statSync(binary)
    const h = crypto.createHash('sha256')
    h.update(fs.readFileSync(binary).subarray(0, 65536))
    return { size: st.size, head: h.digest('hex').slice(0, 16) }
  } catch {
    return null
  }
}

export function verifyLock(root) {
  const lock = readLock(root)
  const problems = []
  for (const t of lock.tools) {
    const binary = findTool(root, t.name)
    if (!binary) {
      problems.push({ tool: t.name, problem: 'missing', detail: `locked but not installed (${t.version || 'unknown'})` })
      continue
    }
    if (t.fingerprint) {
      const fp = versionFingerprint(binary)
      if (fp && t.fingerprint.head && fp.head !== t.fingerprint.head) {
        problems.push({ tool: t.name, problem: 'changed', detail: 'binary changed since it was locked; re-run oi tools lock' })
      }
    }
  }
  return { ok: problems.length === 0, problems, tools: lock.tools, file: lock.file, exists: lock.exists }
}

export function writeLock(root, tools) {
  const file = workspacePaths(root).lock
  const body = stringifyToml({ tool: tools })
  fs.writeFileSync(file, `# generated by openinfra; see docs/phased.md P2\n${body}\n`)
  return file
}
